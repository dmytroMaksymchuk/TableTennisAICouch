"""File-system job repository (DESIGN §5, §6.3). All JSON writes are `.tmp` + `os.replace`."""

from __future__ import annotations

import json
import os
import secrets
import shutil
import threading
import time
from collections.abc import Callable
from datetime import UTC, datetime
from pathlib import Path
from typing import Any, BinaryIO, Protocol, TypeVar

from ttcoach.errors import JobNotFound, UploadTooLarge
from ttcoach.jobs.models import Job, JobSettings, utc_now

CHUNK = 1024 * 1024
T = TypeVar("T")


def retry_sharing(fn: Callable[[], T], attempts: int = 100, delay_s: float = 0.01) -> T:
    """Windows: os.replace and concurrent opens of the same file fail transiently with a sharing
    violation (PermissionError) while the other side holds the file; retry briefly."""
    for i in range(attempts):
        try:
            return fn()
        except PermissionError:
            if i == attempts - 1:
                raise
            time.sleep(delay_s)
    raise AssertionError("unreachable")


def write_json_atomic(path: Path, obj: Any) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_name(path.name + ".tmp")
    with open(tmp, "w", encoding="utf-8") as f:
        json.dump(obj, f, ensure_ascii=False, separators=(",", ":"))
    retry_sharing(lambda: os.replace(tmp, path))


class JobRepository(Protocol):
    def create(self, settings: JobSettings, upload: BinaryIO, filename: str) -> Job: ...
    def get(self, job_id: str) -> Job: ...
    def list(self) -> list[Job]: ...
    def update(self, job_id: str, **changes: Any) -> Job: ...
    def path(self, job_id: str, rel: str) -> Path: ...
    def write_json(self, job_id: str, rel: str, obj: Any) -> None: ...
    def read_json(self, job_id: str, rel: str) -> Any: ...


class FileJobRepository:
    def __init__(self, data_dir: Path) -> None:
        self.root = Path(data_dir) / "jobs"
        self.root.mkdir(parents=True, exist_ok=True)
        self._locks: dict[str, threading.Lock] = {}
        self._locks_guard = threading.Lock()

    def _lock(self, job_id: str) -> threading.Lock:
        with self._locks_guard:
            return self._locks.setdefault(job_id, threading.Lock())

    def _job_dir(self, job_id: str) -> Path:
        # job ids are generated by us; reject anything that could escape the root.
        if not job_id or any(c in job_id for c in "/\\.:") or len(job_id) > 64:
            raise JobNotFound(job_id)
        return self.root / job_id

    @staticmethod
    def new_id() -> str:
        return datetime.now(UTC).strftime("%Y%m%dT%H%M%S-") + secrets.token_hex(3)

    def create(
        self,
        settings: JobSettings,
        upload: BinaryIO,
        filename: str,
        *,
        max_bytes: int | None = None,
        before_commit: Callable[[str, Path], None] | None = None,
    ) -> Job:
        """Stream the upload to input/original.<ext>, run `before_commit(job_id, input_path)` (validation),
        then write job.json last — a job without job.json is never seen by list() or restart recovery.
        On any error the job directory is removed. Raises UploadTooLarge when more than max_bytes arrive."""
        ext = Path(filename).suffix.lower()
        while True:
            # Claim the id atomically; on a collision another request owns that dir — never touch it.
            job_id = self.new_id()
            job_dir = self.root / job_id
            try:
                job_dir.mkdir(exist_ok=False)
                break
            except FileExistsError:
                continue
        try:
            (job_dir / "input").mkdir()
            written = 0
            input_path = job_dir / "input" / f"original{ext}"
            with open(input_path, "wb") as out:
                while chunk := upload.read(CHUNK):
                    written += len(chunk)
                    if max_bytes is not None and written > max_bytes:
                        raise UploadTooLarge(max_bytes)
                    out.write(chunk)
            if before_commit is not None:
                before_commit(job_id, input_path)
            job = Job(id=job_id, settings=settings, original_filename=filename)
            write_json_atomic(job_dir / "job.json", job.model_dump(mode="json"))
        except BaseException:
            shutil.rmtree(job_dir, ignore_errors=True)
            raise
        return job

    def input_path(self, job_id: str) -> Path:
        matches = sorted((self._job_dir(job_id) / "input").glob("original.*"))
        if not matches:
            raise FileNotFoundError(f"no input video for job {job_id}")
        return matches[0]

    def get(self, job_id: str) -> Job:
        p = self._job_dir(job_id) / "job.json"
        try:
            return Job.model_validate_json(retry_sharing(p.read_bytes))
        except FileNotFoundError:
            raise JobNotFound(job_id) from None

    def list(self) -> list[Job]:
        jobs = []
        for d in self.root.iterdir():
            if (d / "job.json").is_file():
                try:
                    jobs.append(self.get(d.name))
                except (ValueError, JobNotFound):
                    continue
        return sorted(jobs, key=lambda j: (j.created_at, j.id), reverse=True)

    def update(self, job_id: str, **changes: Any) -> Job:
        with self._lock(job_id):
            data = self.get(job_id).model_dump(mode="json")
            data.update(changes)
            data["updated_at"] = utc_now()
            job = Job.model_validate(data)
            write_json_atomic(self._job_dir(job_id) / "job.json", job.model_dump(mode="json"))
            return job

    def delete(self, job_id: str) -> None:
        shutil.rmtree(self._job_dir(job_id), ignore_errors=True)

    def path(self, job_id: str, rel: str) -> Path:
        return self._job_dir(job_id) / rel

    def write_json(self, job_id: str, rel: str, obj: Any) -> None:
        write_json_atomic(self.path(job_id, rel), obj)

    def read_json(self, job_id: str, rel: str) -> Any:
        return json.loads(retry_sharing(self.path(job_id, rel).read_bytes))
